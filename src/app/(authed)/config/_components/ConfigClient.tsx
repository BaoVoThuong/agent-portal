function requiredColumnTitle(
  column: Pick<TableColumn, "is_system" | "scope" | "key">,
  scope: TableScope
): string | undefined {
  if (isAutoGeneratedColumn(column)) {
    return "This column has no create-time input, so Required has nothing to check.";
  }
  if (!column.is_system && (scope === "aca" || scope === "medicare")) {
    return "Create does not render custom inputs yet; Required is checked only when a supported flow supplies this custom value.";
  }
  return undefined;
}

