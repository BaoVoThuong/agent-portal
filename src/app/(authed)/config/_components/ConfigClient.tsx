function ConfigDropdownValuesSection({
  scope,
  columns,
  options,
  categories,
  optionSets,
  optionsBySet,
  busy,
  available,
  availabilityError,
  categoriesAvailable,
  categoriesError,
  run,
  refreshScope,
  onCategoriesChange,
  onOptionDataChange,
}: {
  scope: TableScope;
  columns: TableColumn[];
  options: TableColumnOption[];
  categories: TaskCategory[];
  optionSets: EnrollmentOptionSet[];
  optionsBySet: EnrollmentOptionsBySet;
  busy: boolean;
  available: boolean;
  availabilityError?: string;
  categoriesAvailable: boolean;
  categoriesError?: string;
  run: (action: () => Promise<unknown>, success: string) => Promise<void>;
  refreshScope: (scope?: TableScope) => Promise<void>;
  onCategoriesChange: Dispatch<SetStateAction<TaskCategory[]>>;
  onOptionDataChange: () => Promise<void>;
}) {
  const [refreshError, setRefreshError] = useState<string | null>(null);
  const categoryRefreshSequenceRef = useRef(0);
  const isEnrollmentScope = scope === "aca" || scope === "medicare";
  // KHÔNG nhận Status/Priority (CS) — cũng is_system+dropdown nhưng giá trị
  // hardcode trong TASK_STATUSES/TASK_PRIORITIES (TS enum), không có bảng để sửa.
  const customDropdownColumns = columns.filter((column) => column.type === "dropdown" && !column.is_system);
  const hasCategory = scope === "cs" && columns.some((column) => column.is_system && column.key === "category");

  const groups: DropdownValueGroup[] = [
    ...(isEnrollmentScope
      ? optionSets.map((set) => ({
          kind: "optionSet" as const,
          key: `set:${set.key}`,
          navLabel: set.label,
          count: (optionsBySet[set.key] ?? []).filter((o) => !o.archived_at).length,
          setKey: set.key,
        }))
      : []),
    ...(hasCategory
      ? [{ kind: "category" as const, key: "category", navLabel: "Category", count: categories.length }]
      : []),
    ...customDropdownColumns.map((column) => ({
      kind: "custom" as const,
      key: `col:${column.id}`,
      navLabel: column.label,
      count: options.filter((o) => o.column_id === column.id && !o.archived_at).length,
      columnId: column.id,
    })),
  ];

  const [selectedKey, setSelectedKey] = useState(groups[0]?.key ?? "");
  const selected = groups.find((g) => g.key === selectedKey) ?? groups[0];
  const categoryUnavailable = selected?.kind === "category" && !categoriesAvailable;
  const controlsDisabled = busy || !available || Boolean(refreshError) || categoryUnavailable;
  const sectionError = refreshError ?? (categoryUnavailable ? categoriesError : availabilityError);
  const isStageGroup = selected?.kind === "optionSet" && selected.setKey === "stage";
  // Dashboard-terminal semantics belong only to the ACA Overview. They are
  // not a shared CS/Medicare workflow rule.
  const isAcaStageGroup = scope === "aca" && isStageGroup;
  const isConsentGroup = selected?.kind === "optionSet" && selected.setKey === "consent";
  const protectsLabelIdentity =
    selected?.kind === "optionSet" && (selected.setKey === "stage" || selected.setKey === "consent");

  const [label, setLabel] = useState("");
  const [color, setColor] = useState("");
  const [usesRecommendedColor, setUsesRecommendedColor] = useState(true);
  const [isTerminal, setIsTerminal] = useState(false);
  const [treatAsTerminal, setTreatAsTerminal] = useState(false);
  const [triggersQc, setTriggersQc] = useState(false);
  const [confirmArchiveId, setConfirmArchiveId] = useState<string | null>(null);
  const [archiveUsage, setArchiveUsage] = useState<{ id: string; count: number } | null>(null);
  const [pendingStageRuleIds, setPendingStageRuleIds] = useState<Set<string>>(new Set());
  const stageRuleQueuesRef = useRef(new Map<string, Promise<void>>());
  const pendingStageRuleCountsRef = useRef(new Map<string, number>());

  const valueRows: DropdownValueRow[] = !selected
    ? []
    : selected.kind === "category"
      ? categories.map((c) => ({ id: c.id, label: c.name, color: c.color }))
      : selected.kind === "custom"
        ? options
            .filter((o) => o.column_id === selected.columnId)
            .map((o) => ({ id: o.id, label: o.label, color: o.color }))
        : sortEnrollmentOptionsByLabel(optionsBySet[selected.setKey] ?? []).map((o) => ({
            id: o.id,
            label: o.label,
            color: o.color,
            isTerminal: o.is_terminal,
            treatAsTerminal: o.treat_as_terminal,
            triggersQc: o.triggers_qc,
          }));
  const activeConsentCount = isConsentGroup ? valueRows.length : 0;
  const recommendedColor = recommendDropdownValueColor(
    valueRows.map((row) => row.color)
  );
  const draftColor = color || recommendedColor;
  const colorAppearance: DropdownValueColorAppearance =
    selected?.kind === "optionSet"
      ? selected.setKey === "stage"
        ? "enrollment-state"
        : "enrollment-identity"
      : "category";

  async function refreshCategories() {
    const requestSequence = categoryRefreshSequenceRef.current + 1;
    categoryRefreshSequenceRef.current = requestSequence;
    try {
      const response = await fetch("/api/tasks/categories", { cache: "no-store" });
      const payload = await readRefreshResponse<unknown>(
        response,
        "Could not refresh task categories."
      );
      if (!isLatestRefresh(requestSequence, categoryRefreshSequenceRef.current)) return;
      if (!payload || typeof payload !== "object" || !Array.isArray((payload as { categories?: unknown }).categories)) {
        throw new Error("Could not refresh task categories.");
      }
      onCategoriesChange((payload as { categories: TaskCategory[] }).categories);
      setRefreshError(null);
    } catch (error) {
      if (!isLatestRefresh(requestSequence, categoryRefreshSequenceRef.current)) return;
      setRefreshError(error instanceof Error ? error.message : "Could not refresh task categories.");
      throw error;
    }
  }

  async function addValue() {
    if (!selected || controlsDisabled) return;
    if (selected.kind === "category") {
      await requestJson("/api/tasks/categories", {
        method: "POST",
        body: JSON.stringify({ name: label, color: draftColor }),
      });
      await refreshCategories();
    } else if (selected.kind === "custom") {
      await requestJson(`/api/config/columns/${selected.columnId}/options`, {
        method: "POST",
        body: JSON.stringify({ label, color: draftColor }),
      });
      await refreshScope(scope);
    } else {
      await requestJson("/api/enrollment/option-sets", {
        method: "POST",
        body: JSON.stringify({
          program: scope,
          set_key: selected.setKey,
          label,
          color: draftColor,
          is_terminal: isTerminal,
          // This flag has meaning only for the ACA Overview. The UI hides it
          // outside ACA, and the guard here prevents stale form state from
          // leaking it into a Medicare option after switching scopes.
          treat_as_terminal: isAcaStageGroup && treatAsTerminal,
          triggers_qc: triggersQc,
        }),
      });
      await onOptionDataChange();
    }
  }

  async function renameValue(id: string, nextLabel: string) {
    if (!selected || controlsDisabled) return;
    if (selected.kind === "category") {
      await requestJson(`/api/tasks/categories/${id}`, { method: "PATCH", body: JSON.stringify({ name: nextLabel }) });
      await refreshCategories();
    } else if (selected.kind === "custom") {
      await requestJson(`/api/config/columns/${selected.columnId}/options/${id}`, {
        method: "PATCH",
        body: JSON.stringify({ label: nextLabel }),
      });
      await refreshScope(scope);
    } else {
      await requestJson(`/api/enrollment/option-sets/${id}`, { method: "PATCH", body: JSON.stringify({ label: nextLabel }) });
      await onOptionDataChange();
    }
  }

  async function recolorValue(id: string, nextColor: string) {
    if (!selected || controlsDisabled) return;
    if (selected.kind === "category") {
      await requestJson(`/api/tasks/categories/${id}`, { method: "PATCH", body: JSON.stringify({ color: nextColor }) });
      await refreshCategories();
    } else if (selected.kind === "custom") {
      await requestJson(`/api/config/columns/${selected.columnId}/options/${id}`, {
        method: "PATCH",
        body: JSON.stringify({ color: nextColor }),
      });
      await refreshScope(scope);
    } else {
      await requestJson(`/api/enrollment/option-sets/${id}`, { method: "PATCH", body: JSON.stringify({ color: nextColor }) });
      await onOptionDataChange();
    }
  }

  async function toggleStageRule(id: string, patch: { is_terminal?: boolean; treat_as_terminal?: boolean; triggers_qc?: boolean }) {
    if (controlsDisabled) return;
    const pendingCount = (pendingStageRuleCountsRef.current.get(id) ?? 0) + 1;
    pendingStageRuleCountsRef.current.set(id, pendingCount);
    setPendingStageRuleIds((current) => new Set(current).add(id));

    const previous = stageRuleQueuesRef.current.get(id) ?? Promise.resolve();
    const operation = previous
      .catch(() => undefined)
      .then(async () => {
        await requestJson(`/api/enrollment/option-sets/${id}`, {
          method: "PATCH",
          body: JSON.stringify(patch),
        });
        await onOptionDataChange();
      });
    stageRuleQueuesRef.current.set(id, operation);
    try {
      await operation;
    } finally {
      const remaining = (pendingStageRuleCountsRef.current.get(id) ?? 1) - 1;
      if (remaining > 0) {
        pendingStageRuleCountsRef.current.set(id, remaining);
      } else {
        pendingStageRuleCountsRef.current.delete(id);
        setPendingStageRuleIds((current) => {
          const next = new Set(current);
          next.delete(id);
          return next;
        });
      }
      if (stageRuleQueuesRef.current.get(id) === operation) {
        stageRuleQueuesRef.current.delete(id);
      }
    }
  }

  async function archiveValue(id: string) {
    if (!selected || controlsDisabled) return;
    if (selected.kind === "category") {
      await requestJson(`/api/tasks/categories/${id}`, { method: "DELETE" });
      await refreshCategories();
    } else if (selected.kind === "custom") {
      await requestJson(`/api/config/columns/${selected.columnId}/options/${id}`, { method: "DELETE" });
      await refreshScope(scope);
    } else {
      await requestJson(`/api/enrollment/option-sets/${id}`, { method: "DELETE" });
      await onOptionDataChange();
    }
  }

  async function prepareArchive(id: string) {
    if (!selected || controlsDisabled) return;
    const selectedSnapshot = selected;
    setArchiveUsage(null);
    if (selectedSnapshot.kind === "category") {
      setConfirmArchiveId(id);
      return;
    }

    const usageUrl = selectedSnapshot.kind === "custom"
      ? `/api/config/columns/${selectedSnapshot.columnId}/options/${id}/usage`
      : `/api/enrollment/option-sets/${id}/usage`;
    const payload = await requestJson(usageUrl, { cache: "no-store" });
    const usageCount = Number(payload?.usage_count);
    if (!Number.isSafeInteger(usageCount) || usageCount < 0) {
      throw new Error("Could not check option usage.");
    }
    // Do not open a confirmation for a different group if the admin changed
    // scope/group while the on-demand request was in flight.
    if (selectedKey !== selectedSnapshot.key) return;
    setArchiveUsage({ id, count: usageCount });
    setConfirmArchiveId(id);
  }

  const confirmRow = valueRows.find((r) => r.id === confirmArchiveId) ?? null;
  const wouldDropConsentBelowTwo = isConsentGroup && activeConsentCount <= 2;

  function resetValueDraft() {
    setLabel("");
    setColor("");
    setUsesRecommendedColor(true);
    setIsTerminal(false);
    setTreatAsTerminal(false);
    setTriggersQc(false);
    setConfirmArchiveId(null);
    setArchiveUsage(null);
  }

  return (
    <section className="overflow-hidden rounded border border-[#dfe1e6] bg-white shadow-sm">
      <div className="border-b border-[#dfe1e6] px-6 py-4">
        <h2 className="text-lg font-bold">Dropdown values</h2>
        <p className="mt-1 text-sm text-[#6b778c]">
          Every dropdown value — custom columns, Category, and Enrollment option
          sets — is managed here in one place.
        </p>
      </div>
      {!available || refreshError || categoryUnavailable ? (
        <ConfigSectionUnavailable message={sectionError} />
      ) : null}
      {groups.length === 0 ? (
        <div className="px-6 py-10 text-sm font-semibold text-[#6b778c]">No dropdown values yet.</div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-[200px_minmax(0,1fr)]">
          <nav className="border-b border-[#dfe1e6] bg-[#f7f8fa] p-3 md:border-b-0 md:border-r">
            {groups.map((group) => (
              <button
                key={group.key}
                type="button"
                onClick={() => {
                  setSelectedKey(group.key);
                  resetValueDraft();
                }}
                className={`mb-1 flex w-full items-center justify-between rounded px-3 py-2 text-left text-sm font-bold transition ${
                  group.key === selected?.key ? "bg-[#e9f2ff] text-[#0c66e4]" : "text-[#42526e] hover:bg-white"
                }`}
              >
                {group.navLabel}
                <span>{group.count}</span>
              </button>
            ))}
          </nav>
          <div className="min-w-0 p-4">
            <form
              className={`grid grid-cols-1 gap-2 border-b border-[#dfe1e6] pb-4 ${
                isAcaStageGroup
                  ? "md:grid-cols-[minmax(0,1fr)_240px_110px_110px_110px_auto]"
                  : isStageGroup
                    ? "md:grid-cols-[minmax(0,1fr)_240px_110px_110px_auto]"
                    : "md:grid-cols-[minmax(0,1fr)_240px_auto]"
              }`}
              onSubmit={(event) => {
                event.preventDefault();
                if (!selected || !label.trim()) return;
                void run(async () => {
                  await addValue();
                  setLabel("");
                  setColor("");
                  setUsesRecommendedColor(true);
                  setIsTerminal(false);
                  setTreatAsTerminal(false);
                  setTriggersQc(false);
                }, "Option added.");
              }}
            >
              <input
                value={label}
                onChange={(event) => setLabel(event.target.value)}
                placeholder={`New ${selected?.navLabel ?? "value"}`}
                className="h-10 rounded border border-[#dfe1e6] px-3 text-sm font-semibold outline-none focus:border-[#0c66e4]"
              />
              <DropdownValueColorControl
                label={label}
                identityKey={`draft:${selected?.key ?? "value"}`}
                color={draftColor}
                fallbackColor={recommendedColor}
                appearance={colorAppearance}
                recommended={usesRecommendedColor}
                disabled={controlsDisabled}
                onRecommendNext={() => {
                  setColor(
                    nextRecommendedDropdownValueColor(
                      draftColor,
                      valueRows.map((row) => row.color)
                    )
                  );
                  setUsesRecommendedColor(true);
                }}
                onColorChange={(nextColor) => {
                  setColor(nextColor);
                  setUsesRecommendedColor(false);
                }}
              />
              {isStageGroup ? (
                <>
                  <label
                    className="flex items-center justify-center gap-2 rounded border border-[#dfe1e6] px-2 text-xs font-bold text-[#42526e]"
                    title="Workflow terminal: entering this stage closes the enrollment record."
                  >
                    <input
                      type="checkbox"
                      disabled={controlsDisabled}
                      checked={isTerminal}
                      onChange={(event) => setIsTerminal(event.target.checked)}
                    />
                    Workflow terminal
                  </label>
                  <label className="flex items-center justify-center gap-2 rounded border border-[#dfe1e6] px-2 text-xs font-bold text-[#42526e]">
                    <input
                      type="checkbox"
                      disabled={controlsDisabled}
                      checked={triggersQc}
                      onChange={(event) => setTriggersQc(event.target.checked)}
                    />
                    QC
                  </label>
                </>
              ) : null}
              {isAcaStageGroup ? (
                <label
                  className="flex items-center justify-center gap-2 rounded border border-[#dfe1e6] px-2 text-xs font-bold text-[#42526e]"
                  title="ACA overview only: excludes this stage from active-work metrics; does not close the enrollment record."
                >
                  <input
                    type="checkbox"
                    disabled={controlsDisabled}
                    checked={treatAsTerminal}
                    onChange={(event) => setTreatAsTerminal(event.target.checked)}
                  />
                  Dashboard terminal (ACA only)
                </label>
              ) : null}
              <button
                type="submit"
                disabled={controlsDisabled || !label.trim() || (isConsentGroup && activeConsentCount >= 2)}
                title={
                  isConsentGroup && activeConsentCount >= 2
                    ? "Consent supports exactly 2 active options (Yes / other)."
                    : undefined
                }
                className="inline-flex h-10 items-center justify-center gap-2 rounded bg-[#0c66e4] px-4 text-sm font-bold text-white disabled:opacity-40"
              >
                <Plus className="h-4 w-4" /> Add
              </button>
            </form>
            <div className="mt-4 min-w-0 overflow-hidden rounded-lg border border-[#dfe1e6]">
              <table className="w-full table-fixed border-collapse text-sm">
                <colgroup>
                  <col className={isStageGroup ? "w-[28%]" : "w-[40%]"} />
                  <col className={isStageGroup ? "w-[32%]" : "w-[45%]"} />
                  {isStageGroup ? <col className="w-[28%]" /> : null}
                  <col className={isStageGroup ? "w-[12%]" : "w-[15%]"} />
                </colgroup>
                <thead className="bg-[#f7f8fa] text-xs font-bold uppercase text-[#6b778c]">
                  <tr>
                    <th className="border-b border-r border-[#dfe1e6] px-3 py-2 text-left">Label</th>
                    <th className="border-b border-r border-[#dfe1e6] px-3 py-2 text-left">Color</th>
                    {isStageGroup ? (
                      <th className="border-b border-r border-[#dfe1e6] px-3 py-2 text-left">Rules</th>
                    ) : null}
                    <th className="border-b border-[#dfe1e6] px-3 py-2 text-right">Action</th>
                  </tr>
                </thead>
                <tbody>
                  {valueRows.map((row) => {
                    const disableArchive = isConsentGroup && wouldDropConsentBelowTwo;
                    return (
                      <tr key={row.id}>
                        <td className="border-b border-r border-[#dfe1e6] px-3 py-2">
                          <input
                            defaultValue={row.label}
                            disabled={controlsDisabled || protectsLabelIdentity}
                            title={
                              protectsLabelIdentity
                                ? "Stage and Consent labels are protected workflow identities."
                                : undefined
                            }
                            onBlur={(event) => {
                              if (protectsLabelIdentity) return;
                              const value = event.target.value.trim();
                              if (value && value !== row.label) void run(() => renameValue(row.id, value), "Option updated.");
                            }}
                            className="h-8 w-full rounded border border-[#dfe1e6] px-2 font-semibold outline-none focus:border-[#0c66e4] disabled:cursor-not-allowed disabled:bg-[#f7f8fa] disabled:text-[#6b778c]"
                          />
                        </td>
                        <td className="border-b border-r border-[#dfe1e6] px-3 py-2">
                          <DropdownValueColorControl
                            key={`color:${row.id}:${row.color ?? "none"}`}
                            label={row.label}
                            identityKey={row.id}
                            color={row.color}
                            fallbackColor={recommendedColor}
                            appearance={colorAppearance}
                            disabled={controlsDisabled}
                            onColorCommit={(nextColor) =>
                              void run(
                                () => recolorValue(row.id, nextColor),
                                "Option updated."
                              )
                            }
                          />
                        </td>
                        {isStageGroup ? (
                          <td className="border-b border-r border-[#dfe1e6] px-3 py-2 text-xs font-semibold text-[#42526e]">
                            <div className="flex flex-wrap gap-2">
                              <label className="flex items-center gap-1.5" title="Workflow terminal: entering this stage closes the enrollment record.">
                                <input
                                  type="checkbox"
                                  disabled={controlsDisabled || pendingStageRuleIds.has(row.id)}
                                  checked={Boolean(row.isTerminal)}
                                  onChange={(event) =>
                                    void run(
                                      () => toggleStageRule(row.id, { is_terminal: event.target.checked }),
                                      "Option updated."
                                    )
                                  }
                                />
                                Workflow terminal
                              </label>
                              {isAcaStageGroup ? (
                                <label className="flex items-center gap-1.5" title="ACA overview only: excludes this stage from active-work metrics; does not close the enrollment record.">
                                  <input
                                    type="checkbox"
                                    disabled={controlsDisabled || pendingStageRuleIds.has(row.id)}
                                    checked={Boolean(row.treatAsTerminal)}
                                    onChange={(event) =>
                                      void run(
                                        () => toggleStageRule(row.id, { treat_as_terminal: event.target.checked }),
                                        "Option updated."
                                      )
                                    }
                                  />
                                  Dashboard terminal (ACA only)
                                </label>
                              ) : null}
                              <label className="flex items-center gap-1.5">
                                <input
                                  type="checkbox"
                                  disabled={controlsDisabled || pendingStageRuleIds.has(row.id)}
                                  checked={Boolean(row.triggersQc)}
                                  onChange={(event) =>
                                    void run(
                                      () => toggleStageRule(row.id, { triggers_qc: event.target.checked }),
                                      "Option updated."
                                    )
                                  }
                                />
                                QC
                              </label>
                            </div>
                          </td>
                        ) : null}
                        <td className="border-b border-[#dfe1e6] px-3 py-2 text-right">
                          <button
                            type="button"
                            disabled={controlsDisabled || disableArchive}
                            title={disableArchive ? "Consent needs at least 2 active options." : undefined}
                            onClick={() => void run(
                              () => prepareArchive(row.id),
                              "Archive confirmation ready."
                            )}
                            className="text-xs font-bold text-[#bf2600] hover:underline disabled:opacity-40 disabled:no-underline"
                          >
                            Archive
                          </button>
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      )}
      {confirmRow ? (
        <ConfirmDialog
          title={`Archive "${confirmRow.label}"?`}
          description={
            selected?.kind === "optionSet" || selected?.kind === "custom"
              ? archiveUsage?.id === confirmRow.id
                ? archiveUsage.count > 0
                  ? `${archiveUsage.count} record(s) currently use this option. Archiving removes it from pickers going forward — those records keep showing it, but nobody can select it for a new record until it's restored.`
                  : "No live records currently use this option. It will be removed from pickers going forward."
                : "Usage could not be verified. Close this dialog and retry before archiving."
              : "This value will be removed from pickers going forward. Existing records that reference it keep showing it."
          }
          confirmLabel="Archive"
          busy={busy}
          onCancel={() => {
            setConfirmArchiveId(null);
            setArchiveUsage(null);
          }}
          onConfirm={() => {
            const id = confirmRow.id;
            setConfirmArchiveId(null);
            setArchiveUsage(null);
            void run(() => archiveValue(id), "Option archived.");
          }}
        />
      ) : null}
    </section>
  );
}

function ConfirmDialog({
  title,
  description,
  confirmLabel,
  busy = false,
  onCancel,
  onConfirm,
}: {
  title: string;
  description: string;
  confirmLabel: string;
  busy?: boolean;
  onCancel: () => void;
  onConfirm: () => void | Promise<void>;
}) {
  const dialogRef = useRef<HTMLDivElement>(null);
  const cancelRef = useRef<HTMLButtonElement>(null);
  const cancelHandlerRef = useRef(onCancel);
  const submittingRef = useRef(false);
  const [submitting, setSubmitting] = useState(false);
  const titleId = useId();
  const descriptionId = useId();

  useEffect(() => {
    cancelHandlerRef.current = onCancel;
  }, [onCancel]);

  useEffect(() => {
    const previousFocus = document.activeElement as HTMLElement | null;
    const previousOverflow = document.body.style.overflow;
    document.body.style.overflow = "hidden";
    cancelRef.current?.focus();

    function onKeyDown(event: KeyboardEvent) {
      if (event.key === "Escape") {
        event.preventDefault();
        if (!submittingRef.current) cancelHandlerRef.current();
        return;
      }
      if (event.key !== "Tab" || !dialogRef.current) return;
      const focusable = Array.from(
        dialogRef.current.querySelectorAll<HTMLElement>(
          'button:not([disabled]), [href], input:not([disabled]), select:not([disabled]), textarea:not([disabled]), [tabindex]:not([tabindex="-1"])'
        )
      );
      if (focusable.length === 0) return;
      const first = focusable[0];
      const last = focusable[focusable.length - 1];
      if (event.shiftKey && document.activeElement === first) {
        event.preventDefault();
        last.focus();
      } else if (!event.shiftKey && document.activeElement === last) {
        event.preventDefault();
        first.focus();
      }
    }

    document.addEventListener("keydown", onKeyDown);
    return () => {
      document.removeEventListener("keydown", onKeyDown);
      document.body.style.overflow = previousOverflow;
      previousFocus?.focus();
    };
  }, []);

  function handleConfirm() {
    if (busy || submitting) return;
    submittingRef.current = true;
    setSubmitting(true);
    void onConfirm();
  }

  return (
    <div
      className="fixed inset-0 z-[90] flex items-center justify-center bg-[#091e42]/50 p-4"
      role="presentation"
      onMouseDown={(event) => {
        if (event.target === event.currentTarget && !busy && !submitting) onCancel();
      }}
    >
      <div
        ref={dialogRef}
        role="dialog"
        aria-modal="true"
        aria-labelledby={titleId}
        aria-describedby={descriptionId}
        className="w-full max-w-sm rounded-lg bg-white p-5 shadow-2xl"
      >
        <h2 id={titleId} className="text-lg font-bold text-[#172b4d]">{title}</h2>
        <p id={descriptionId} className="mt-2 text-sm leading-6 text-[#5e6c84]">{description}</p>
        <div className="mt-5 flex justify-end gap-2">
          <button
            type="button"
            ref={cancelRef}
            onClick={onCancel}
            disabled={busy || submitting}
            className="rounded px-3 py-2 text-sm font-bold text-[#42526e] transition hover:bg-[#f4f5f7]"
          >
            Cancel
          </button>
          <button
            type="button"
            onClick={handleConfirm}
            disabled={busy || submitting}
            className="rounded bg-[#ca3521] px-3 py-2 text-sm font-bold text-white shadow-sm transition hover:bg-[#ae2a19] disabled:cursor-not-allowed disabled:opacity-60"
          >
            {busy || submitting ? "Working…" : confirmLabel}
          </button>
        </div>
      </div>
    </div>
  );
}

function ConfigAssistantSection({
  agents,
  candidates,
  assignees,
  members,
  busy,
  available,
  availabilityError,
  run,
  setMembers,
  onAgentsChange,
}: {
  agents: TaskAgent[];
  candidates: TaskAssignee[];
  assignees: TaskAssignee[];
  members: AssistantMember[];
  busy: boolean;
  available: boolean;
  availabilityError?: string;
  run: (action: () => Promise<unknown>, success: string) => Promise<void>;
  setMembers: Dispatch<SetStateAction<AssistantMember[]>>;
  onAgentsChange: Dispatch<SetStateAction<TaskAgent[]>>;
}) {
  const [agentEmail, setAgentEmail] = useState(agents[0]?.email ?? "");
  const [assistantEmail, setAssistantEmail] = useState("");
  const [newAgentEmail, setNewAgentEmail] = useState("");
  const [agentsRefreshError, setAgentsRefreshError] = useState<string | null>(null);
  const [membersRefreshError, setMembersRefreshError] = useState<string | null>(null);
  const agentsRefreshSequenceRef = useRef(0);
  const membersRefreshSequenceRef = useRef(0);
  const agentsControlsDisabled = busy || !available || Boolean(agentsRefreshError);
  const membersControlsDisabled =
    busy || !available || Boolean(agentsRefreshError) || Boolean(membersRefreshError);
  const agentEmails = new Set(agents.map((a) => a.email));
  // Agent picker: MỌI account active (khớp AgentGroupsModal cũ) — Agent không
  // bắt buộc có quyền task.work, họ có thể chưa từng dùng CS board.
  const agentCandidateOptions: SelectOption<string>[] = [
    { value: "", label: "Select person" },
    ...candidates
      .filter((person) => !agentEmails.has(person.email))
      .map((person) => ({ value: person.email, label: person.name?.trim() || person.email })),
  ];

  async function refreshAgents() {
    if (!available) return;
    const requestSequence = agentsRefreshSequenceRef.current + 1;
    agentsRefreshSequenceRef.current = requestSequence;
    try {
      const response = await fetch("/api/config/agents", { cache: "no-store" });
      const payload = await readRefreshResponse<unknown>(response, "Could not refresh agents.");
      if (!isLatestRefresh(requestSequence, agentsRefreshSequenceRef.current)) return;
      if (!payload || typeof payload !== "object" || !Array.isArray((payload as { agents?: unknown }).agents)) {
        throw new Error("Could not refresh agents.");
      }
      onAgentsChange((payload as { agents: TaskAgent[] }).agents);
      setAgentsRefreshError(null);
    } catch (error) {
      if (!isLatestRefresh(requestSequence, agentsRefreshSequenceRef.current)) return;
      setAgentsRefreshError(error instanceof Error ? error.message : "Could not refresh agents.");
      throw error;
    }
  }

  // Gộp cả 2 nguồn để label luôn resolve được tên — member.agent_email có thể
  // thuộc `candidates` (mọi account), member.cs_email chỉ thuộc `assignees`
  // (task-work roster). labelForEmail() fallback về raw email nếu không thấy.
  const candidateByEmail = useMemo(
    () => new Map([...candidates, ...assignees].map((person) => [person.email, person])),
    [candidates, assignees]
  );
  const agentOptions: SelectOption<string>[] = agents.map((agent) => ({
    value: agent.email,
    label: agent.name?.trim() || agent.email,
  }));
  // Assistant picker: CHỈ người có task.work/task.manage (khớp AgentGroupsModal
  // cũ, prop `cs`) — làm Assistant = được cấp quyền ngang agent-owner trên task
  // của agent đó, người không có quyền task.work không vào được /tasks nên
  // gán họ làm Assistant là vô nghĩa.
  const existingAssistantEmails = new Set(
    members
      .filter((member) => member.agent_email === agentEmail && member.is_assistant)
      .map((member) => member.cs_email)
  );
  const assistantOptions: SelectOption<string>[] = [
    { value: "", label: "Select assistant" },
    ...assignees.filter(
      (person) => person.email !== agentEmail && !existingAssistantEmails.has(person.email)
    ).map((person) => ({
      value: person.email,
      label: person.name?.trim() || person.email,
    })),
  ];
  // Hiện TẤT CẢ quan hệ agent→assistant, sắp theo tên agent rồi tên assistant
  // — dropdown "Agent" bên trên chỉ dùng để tạo mới, không lọc list này, để
  // admin xem được toàn bộ cấu trúc team trong 1 lần nhìn.
  const memberRows = [...members].sort((a, b) => {
    const agentCompare = labelForEmail(a.agent_email, candidateByEmail).localeCompare(
      labelForEmail(b.agent_email, candidateByEmail)
    );
    if (agentCompare !== 0) return agentCompare;
    return labelForEmail(a.cs_email, candidateByEmail).localeCompare(
      labelForEmail(b.cs_email, candidateByEmail)
    );
  });

  async function refreshMembers() {
    if (!available) return;
    const requestSequence = membersRefreshSequenceRef.current + 1;
    membersRefreshSequenceRef.current = requestSequence;
    try {
      const response = await fetch("/api/config/assistants", { cache: "no-store" });
      const payload = await readRefreshResponse<unknown>(
        response,
        "Could not refresh assistant memberships."
      );
      if (!isLatestRefresh(requestSequence, membersRefreshSequenceRef.current)) return;
      if (!payload || typeof payload !== "object" || !Array.isArray((payload as { members?: unknown }).members)) {
        throw new Error("Could not refresh assistant memberships.");
      }
      setMembers((payload as { members: AssistantMember[] }).members);
      setMembersRefreshError(null);
    } catch (error) {
      if (!isLatestRefresh(requestSequence, membersRefreshSequenceRef.current)) return;
      setMembersRefreshError(
        error instanceof Error ? error.message : "Could not refresh assistant memberships."
      );
      throw error;
    }
  }

  return (
    <>
      <section className="overflow-hidden rounded border border-[#dfe1e6] bg-white shadow-sm">
        <div className="border-b border-[#dfe1e6] px-6 py-4">
          <h2 className="text-lg font-bold">Agents</h2>
          <p className="mt-1 text-sm text-[#6b778c]">
            Add people as Agents. Removing an agent also unlinks all of their assistants.
          </p>
        </div>
        {!available || agentsRefreshError ? (
          <ConfigSectionUnavailable message={agentsRefreshError ?? availabilityError} />
        ) : null}
        <form
          className="grid gap-3 border-b border-[#dfe1e6] bg-[#fafbfc] p-4 md:grid-cols-[1fr_120px]"
          onSubmit={(event) => {
            event.preventDefault();
            if (!newAgentEmail) return;
            void run(async () => {
              await requestJson("/api/config/agents", {
                method: "POST",
                body: JSON.stringify({ email: newAgentEmail }),
              });
              setNewAgentEmail("");
              await refreshAgents();
            }, "Agent added.");
          }}
        >
          <DropdownSelect
            label="Person"
            value={newAgentEmail}
            options={agentCandidateOptions}
            onChange={setNewAgentEmail}
            placeholder="Select person"
          />
          <button
            type="submit"
            disabled={agentsControlsDisabled || !newAgentEmail}
            className="inline-flex h-10 items-center justify-center gap-2 rounded bg-[#0c66e4] px-4 text-sm font-bold text-white disabled:opacity-50"
          >
            <Plus className="h-4 w-4" /> Add
          </button>
        </form>
        {agents.map((agent) => (
          <div
            key={agent.email}
            className="grid grid-cols-[1fr_140px] items-center border-b border-[#ebecf0] px-4 py-2 last:border-b-0"
          >
            <div>
              <p className="text-sm font-bold">{agent.name?.trim() || agent.email}</p>
              <p className="text-xs font-semibold text-[#6b778c]">{agent.email}</p>
            </div>
            <button
              type="button"
              disabled={agentsControlsDisabled}
              onClick={() =>
                void run(async () => {
                  await requestJson("/api/config/agents", {
                    method: "DELETE",
                    body: JSON.stringify({ email: agent.email }),
                  });
                  await refreshAgents();
                  // Xoá agent cascade-xoá agent_members ở server — refresh
                  // luôn danh sách assistant để không còn row mồ côi trên UI.
                  await refreshMembers();
                }, "Agent removed.")
              }
              className="inline-flex w-fit items-center gap-1 rounded px-2 py-1 text-sm font-bold text-[#bf2600] hover:bg-[#ffebe6]"
            >
              <Trash2 className="h-4 w-4" /> Remove
            </button>
          </div>
        ))}
      </section>

      <section className="overflow-hidden rounded border border-[#dfe1e6] bg-white shadow-sm">
        <div className="border-b border-[#dfe1e6] px-6 py-4">
          <h2 className="text-lg font-bold">Assistant membership</h2>
          <p className="mt-1 text-sm text-[#6b778c]">
            Link an existing Agent to the people who assist them.
          </p>
        </div>
        {!available || agentsRefreshError || membersRefreshError ? (
          <ConfigSectionUnavailable
            message={agentsRefreshError ?? membersRefreshError ?? availabilityError}
          />
        ) : null}
        <form
          className="grid gap-3 border-b border-[#dfe1e6] bg-[#fafbfc] p-4 md:grid-cols-[280px_1fr_120px]"
          onSubmit={(event) => {
            event.preventDefault();
            void run(async () => {
              await requestJson("/api/config/assistants", {
                method: "POST",
                body: JSON.stringify({ agent_email: agentEmail, cs_email: assistantEmail }),
              });
              setAssistantEmail("");
              await refreshMembers();
            }, "Assistant added.");
          }}
        >
          <DropdownSelect
          label="Agent"
          value={agentEmail}
          options={agentOptions}
          onChange={setAgentEmail}
          placeholder="Select agent"
        />
        <DropdownSelect
          label="Assistant"
          value={assistantEmail}
          options={assistantOptions}
          onChange={setAssistantEmail}
          placeholder="Select assistant"
        />
        <button
          type="submit"
            disabled={membersControlsDisabled || !agentEmail || !assistantEmail}
          className="inline-flex h-10 items-center justify-center gap-2 rounded bg-[#0c66e4] px-4 text-sm font-bold text-white disabled:opacity-50"
        >
          <Plus className="h-4 w-4" /> Add
        </button>
      </form>
      {memberRows.map((member) => (
        <div
          key={`${member.agent_email}:${member.cs_email}`}
          className="grid grid-cols-[1fr_140px] items-center border-b border-[#ebecf0] px-4 py-2 last:border-b-0"
        >
          <div>
            <p className="text-sm font-bold">{labelForEmail(member.cs_email, candidateByEmail)}</p>
            <p className="text-xs font-semibold text-[#6b778c]">
              Assistant to {labelForEmail(member.agent_email, candidateByEmail)}
            </p>
          </div>
          <button
            type="button"
            disabled={membersControlsDisabled}
            onClick={() =>
              void run(async () => {
                await requestJson("/api/config/assistants", {
                  method: "DELETE",
                  body: JSON.stringify({
                    agent_email: member.agent_email,
                    cs_email: member.cs_email,
                  }),
                });
                await refreshMembers();
              }, "Assistant removed.")
            }
            className="inline-flex w-fit items-center gap-1 rounded px-2 py-1 text-sm font-bold text-[#bf2600] hover:bg-[#ffebe6]"
          >
            <Trash2 className="h-4 w-4" /> Remove
          </button>
        </div>
      ))}
      </section>
    </>
  );
}

async function requestJson(url: string, init: RequestInit = {}) {
  const response = await fetch(url, {
    ...init,
    headers: {
      "Content-Type": "application/json",
      ...(init.headers ?? {}),
    },
  });
  const payload = await response.json().catch(() => ({}));
  if (!response.ok) {
    const error = new Error(payload.error ?? "Request failed.") as RequestJsonError;
    error.code = typeof payload.code === "string" ? payload.code : undefined;
    error.payload = payload;
    throw error;
  }
  return payload;
}

type RequestJsonError = Error & {
  code?: string;
  payload?: RequestJsonPayload;
};

type RequestJsonPayload = {
  [key: string]: unknown;
  archived_column?: {
    id?: unknown;
    label?: unknown;
    type?: unknown;
  };
};

function labelForEmail(
  email: string,
  peopleByEmail: ReadonlyMap<string, { name: string | null }>
): string {
  return peopleByEmail.get(email)?.name?.trim() || email;
}
